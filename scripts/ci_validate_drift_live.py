#!/usr/bin/env python3
"""Fail-closed gate for data/drift_live.json (the command-centre feed) and data/hazard_evaluation.json.
Usage: ci_validate_drift_live.py [drift_live.json] [--max-age-minutes N] [--require-cells]"""
import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from backend import forecast_integrity as fi  # noqa: E402

BANNED = ("thunderstorm_probability", "flash_flood_probability", "cloudburst_probability", "subscriber", "@")


def check(path, max_age_min=None, require_cells=False, now=None):
    now = now or datetime.now(timezone.utc)
    v = []
    try:
        d = json.load(open(path))
    except Exception as e:  # noqa: BLE001
        return [f"unreadable: {e}"]
    if d.get("schema") != "drift_live_v1" or d.get("mode") != "LIVE_OPERATIONAL":
        v.append("schema/mode not drift_live_v1 LIVE_OPERATIONAL")
    gen = fi.parse_utc(d.get("generated_at_utc"))
    if gen is None:
        v.append("generated_at_utc missing")
    elif max_age_min is not None and (now - gen).total_seconds() / 60 > max_age_min:
        v.append(f"feed older than {max_age_min} min: it was not regenerated by this run")
    blob = json.dumps(d)
    for b in BANNED:
        if b in blob:
            v.append(f"banned content: {b}")
    hz = d.get("hazards") or {}
    if set(hz) != {"thunderstorm", "extreme_rainfall", "flash_flood"}:
        v.append("hazards must be exactly thunderstorm/extreme_rainfall/flash_flood")
    elif hz["flash_flood"].get("status") != "UNAVAILABLE":
        v.append("flash_flood must be UNAVAILABLE until a validated target exists")
    a = d.get("alerts") or {}
    if a.get("automated_dispatch") != "DISABLED" or a.get("eligible", 1) != 0:
        v.append("production alert policy must show automated dispatch DISABLED with 0 eligible")
    ids = {s.get("id") for s in d.get("sources") or []}
    if not {"gfs_grid", "cb_daily_outlook", "vobl_station"} <= ids:
        v.append("sources incomplete")
    cells = (d.get("grid") or {}).get("cells") or []
    cols = (d.get("grid") or {}).get("columns") or []
    if require_cells and not cells:
        v.append("no grid cells (source failed integrity or is missing)")
    if any(len(c) != len(cols) for c in cells):
        v.append("ragged cell rows")
    for s in d.get("sources") or []:
        if s.get("state") not in ("FRESH", "STALE", "UNAVAILABLE"):
            v.append(f"bad state for {s.get('id')}")
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("path", nargs="?", default="data/drift_live.json")
    ap.add_argument("--max-age-minutes", type=float)
    ap.add_argument("--require-cells", action="store_true")
    a = ap.parse_args()
    v = check(a.path, a.max_age_minutes, a.require_cells)
    ev = Path(a.path).parent / "hazard_evaluation.json"
    if not ev.exists():
        v.append("hazard_evaluation.json missing")
    if v:
        print("NOT OK:", *v, sep="\n  - ")
        sys.exit(1)
    print(f"OK: {a.path} satisfies the DRIFT live-feed contract")


if __name__ == "__main__":
    main()
