#!/usr/bin/env python3
"""
Repository inventory: classifies every tracked file and counts ACTIVE references to it, so cleanup/moves are decided by
evidence rather than by age or name. Writes docs/architecture/REPOSITORY_INVENTORY.md and a JSON copy beside it.

Active reference = another tracked file (outside docs/ and the dated SIH_* snapshot folders) that mentions the file's
basename or, for Python, its module stem as a whole word: workflows, scripts, tests, HTML/JS, configs.
A file with zero active references is a CANDIDATE only; the history and workflows must still be checked by a human.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

RULES = [  # first match wins
    (r"^(docs/|README|CONTRIBUTING|DEMO_GUIDE|.*_REPORT\.md$|MASTER_AUDIT)", "documentation"),
    (r"^SIH_[A-Z_]+_\d{8}_\d{6}Z/", "historical snapshot (dated)"),
    (r"^\.github/", "automated workflow / repo config"),
    (r"^(tests/|test_.*\.py$|pytest\.ini)", "tests"),
    (r"^(index\.html|drift\.html|sw\.js|manifest\.json|assets/|pages/|netlify\.toml)", "application frontend / static"),
    (r"^backend/models/", "machine learning (model code)"),
    (r"^backend/", "backend / API"),
    (r"^worker/", "backend / API (edge worker)"),
    (r"^models/", "model artifacts (checkpoints, metrics)"),
    (r"^(data/(ctt_grid|gfs_realtime|upperair|himawari)|forecast\.json|alert_log\.json)", "generated forecast artifact"),
    (r"^data/india_|^data/pan_india|^data/canonical|^data/unified|^data/drift_live|^data/hazard_eval|^data/.*_evaluation", "generated published artifact"),
    (r"^(data/external|imd_rain/|processed/|data/.*\.csv$|data/.*historical)", "historical / training dataset"),
    (r"^data/", "data (reference or generated)"),
    (r"^(dev/|notebooks/)", "development / research (legacy)"),
    (r"^results/", "evaluation outputs (legacy)"),
    (r"^rag/", "retrieval assistant (experimental)"),
    (r"^schemas/", "configuration / schemas"),
    (r"^scripts/diagnostics|^scripts/.*diagnostic", "debugging utility"),
    (r"^scripts/", "pipeline / utility scripts"),
    (r"^(train_|tune_|A\d)", "machine learning and model training"),
    (r"^(forecast_action|gfs_fetcher|pan_india_gfs_fetcher|fetch_|gfs_row_select|lead_time|terrain_lookup|regrid|wind_shear)", "weather data ingestion / processing"),
    (r"^(send_alerts|generate_alert_log|verify_today|populate_skill|compute_realtime|canonical_forecast|validate_canonical|forecast_log|atomic_write|clean_stale)", "forecast production / operations"),
    (r"^(repo_cleanup|phase_0_4)", "temporary / one-off"),
]


def classify(p: str) -> str:
    for pat, label in RULES:
        if re.search(pat, p):
            return label
    return "other"


def main():
    files = subprocess.check_output(["git", "ls-files"], cwd=ROOT, text=True).splitlines()
    text_ext = {".py", ".js", ".mjs", ".html", ".yml", ".yaml", ".json", ".toml", ".ini", ".sh", ".md", ".txt", ".cfg"}
    rows = []
    for f in files:
        p = ROOT / f
        size = p.stat().st_size if p.exists() else 0
        stem = Path(f).stem
        names = {Path(f).name}
        if f.endswith(".py"):
            names.add(stem)
        refs = set()
        if size < 50_000_000:
            for n in names:
                if len(n) < 4:
                    continue
                try:
                    out = subprocess.run(["git", "grep", "-l", "-w", "-F", n, "--", ".", ":!docs", ":!SIH_*", ":!audit"], cwd=ROOT, capture_output=True, text=True).stdout.split()
                except Exception:
                    out = []
                refs |= {o for o in out if o != f and Path(o).suffix in text_ext}
        rows.append({"path": f, "class": classify(f), "kb": round(size / 1024, 1), "active_refs": len(refs), "ref_sample": sorted(refs)[:3]})
    by = defaultdict(lambda: [0, 0.0])
    for r in rows:
        by[r["class"]][0] += 1; by[r["class"]][1] += r["kb"]
    out = ["# Repository inventory (generated)\n",
           "Generated by `scripts/diagnostics/inventory_repository.py` from `git ls-files`. **Active references** count other tracked files "
           "(outside docs and dated snapshots) that mention the file's name or Python module name. Zero references marks a *candidate* for review, never an automatic deletion.\n",
           f"{len(rows)} tracked files, {sum(r['kb'] for r in rows)/1024:.0f} MB.\n", "## By classification\n", "| Class | Files | Size MB |\n|---|---|---|"]
    for k, (n, kb) in sorted(by.items(), key=lambda x: -x[1][1]):
        out.append(f"| {k} | {n} | {kb/1024:.1f} |")
    out += ["\n## Largest tracked files\n", "| File | MB | Class | Active refs |\n|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: -r["kb"])[:25]:
        out.append(f"| `{r['path']}` | {r['kb']/1024:.1f} | {r['class']} | {r['active_refs']} |")
    cand = [r for r in rows if r["active_refs"] == 0 and r["class"] not in ("documentation", "tests", "historical snapshot (dated)", "generated forecast artifact", "generated published artifact", "model artifacts (checkpoints, metrics)", "application frontend / static")
            and not r["path"].endswith((".md", ".csv", ".png", ".json"))]
    out += [f"\n## Zero-reference code/config candidates ({len(cand)})\n", "| File | KB | Class |\n|---|---|---|"]
    for r in sorted(cand, key=lambda r: r["path"])[:200]:
        out.append(f"| `{r['path']}` | {r['kb']} | {r['class']} |")
    (ROOT / "docs" / "architecture").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "architecture" / "REPOSITORY_INVENTORY.md").write_text("\n".join(out) + "\n")
    (ROOT / "docs" / "architecture" / "repository_inventory.json").write_text(json.dumps(rows, indent=0))
    print(f"{len(rows)} files; {len(cand)} zero-reference code/config candidates")
    print(Counter(r['class'] for r in rows).most_common(8))


if __name__ == "__main__":
    main()
